#!/usr/bin/env node
/* Regenerates data/manual-pages.js from a local copy of the manual PDF.
 *
 * The manual prints section-relative page labels ("2-15") in its footers, and
 * that is what every question in the bank cites. A PDF viewer's #page=
 * fragment wants the physical page index instead, so the app needs a map
 * between the two. This walks the PDF, reads the label out of each page's
 * footer, and writes the result out as a plain script the page can load.
 *
 * Usage: node tools/gen-manual-pages.js [path-to-manual.pdf]
 * Needs pdftotext (poppler-utils) on PATH. The PDF is not in the repo; grab it
 * from the NCDOT link in the README first.
 *
 * Two footer labels repeat in the July 2014 manual: pages 1-8 through 1-12
 * appear twice (the older ELDT insert reuses them) and a couple of
 * "intentionally left blank" pages carry the previous label. First occurrence
 * wins here; questions drawn from a later duplicate carry their own pdfPage. */
const { execFileSync } = require('child_process');
const fs = require('fs');
const path = require('path');

const pdf = process.argv[2] || path.join(__dirname, '..', 'commercial-driver-manual.pdf');
if (!fs.existsSync(pdf)) {
  console.error(`${pdf} not found. Download the manual PDF first, or pass its path.`);
  process.exit(1);
}

const text = execFileSync('pdftotext', ['-layout', pdf, '-'], { maxBuffer: 64 * 1024 * 1024 }).toString();
const pages = text.split('\f');
const map = {};
for (let i = 0; i < pages.length; i++) {
  const lines = pages[i].split('\n');
  // The label sits in the footer, on the same line as the section name.
  for (const line of lines.slice(-8)) {
    const m = /Page (\d+(?:-\d+)+)\s*$/.exec(line.trimEnd());
    if (m && !(m[1] in map)) map[m[1]] = i + 1;
  }
}
// Section 8 numbers its pages 8-8-1 .. 8-8-4; the bank cites the whole run as
// "8-8", so point that at the first page of the section.
if (map['8-8-1'] && !map['8-8']) map['8-8'] = map['8-8-1'];

const labels = Object.keys(map).filter(l => /^\d+-\d+$/.test(l))
  .sort((a, b) => {
    const [as, ap] = a.split('-').map(Number);
    const [bs, bp] = b.split('-').map(Number);
    return as - bs || ap - bp;
  });
const body = labels.map(l => `  '${l}': ${map[l]},`).join('\n');
const out = `/* Generated by tools/gen-manual-pages.js. Do not edit by hand.
   Maps the manual's printed page labels ("2-15") to physical page numbers in
   the NCDOT PDF, so a citation can deep link with #page=. Regenerate whenever
   NCDOT publishes a new revision of the manual. */
const MANUAL_PAGES = {
${body}
};
`;
const dest = path.join(__dirname, '..', 'data', 'manual-pages.js');
fs.writeFileSync(dest, out);
console.log(`wrote ${labels.length} page labels to ${path.relative(process.cwd(), dest)}`);
